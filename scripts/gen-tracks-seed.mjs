// Generates supabase/seed_tracks.sql from scripts/curriculum.mjs.
// Idempotent upserts on natural keys (track.slug, module (track,slug),
// topic (module,slug)). Re-run then re-load to update content.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { tracks } from './curriculum.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'supabase', 'seed_tracks.sql');

const q = (s) => `'${String(s ?? '').replace(/'/g, "''")}'`;
const jb = (o) => `${q(JSON.stringify(o ?? []))}::jsonb`;

let sql = `-- Generated by scripts/gen-tracks-seed.mjs — do not edit by hand.\nbegin;\n\n`;
let mCount = 0;
let tCount = 0;

for (const [ti, t] of tracks.entries()) {
  sql +=
    `insert into public.tracks (slug, title, subtitle, description, icon, color, difficulty, status, sort_order)\n` +
    `values (${q(t.slug)}, ${q(t.title)}, ${q(t.subtitle)}, ${q(t.description)}, ${q(t.icon)}, ${q(t.color)}, ${q(t.difficulty)}, 'published', ${t.sortOrder ?? ti})\n` +
    `on conflict (slug) do update set title=excluded.title, subtitle=excluded.subtitle,\n` +
    `  description=excluded.description, icon=excluded.icon, color=excluded.color,\n` +
    `  difficulty=excluded.difficulty, status=excluded.status, sort_order=excluded.sort_order;\n\n`;

  for (const [mi, m] of t.modules.entries()) {
    mCount += 1;
    sql +=
      `insert into public.modules (track_id, slug, title, goal, sort_order)\n` +
      `values ((select id from public.tracks where slug=${q(t.slug)}), ${q(m.slug)}, ${q(m.title)}, ${q(m.goal)}, ${mi})\n` +
      `on conflict (track_id, slug) do update set title=excluded.title, goal=excluded.goal, sort_order=excluded.sort_order;\n`;

    for (const [pi, p] of m.topics.entries()) {
      tCount += 1;
      sql +=
        `insert into public.topics (module_id, slug, title, description, est_hours, resources, status, sort_order)\n` +
        `values ((select mo.id from public.modules mo join public.tracks tr on tr.id=mo.track_id where tr.slug=${q(t.slug)} and mo.slug=${q(m.slug)}), ` +
        `${q(p.slug)}, ${q(p.title)}, ${q(p.description)}, ${p.estHours ?? 2}, ${jb(p.resources)}, 'published', ${pi})\n` +
        `on conflict (module_id, slug) do update set title=excluded.title, description=excluded.description,\n` +
        `  est_hours=excluded.est_hours, resources=excluded.resources, status=excluded.status, sort_order=excluded.sort_order;\n`;
    }
    sql += `\n`;
  }
}

sql += `commit;\n`;
writeFileSync(out, sql);
console.log(`Wrote ${out}: ${tracks.length} tracks, ${mCount} modules, ${tCount} topics.`);
