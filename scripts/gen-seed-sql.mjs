import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const root = '/home/bharathr/self/Learning/learn=12/ai-engineer-365';
const plannerDir = `${root}/planner`;
const outFile = `${root}/supabase/seed.sql`;

const q = (s) => `'${String(s ?? '').replace(/'/g, "''")}'`;
const arr = (list) =>
  !list || list.length === 0 ? `'{}'::text[]` : `array[${list.map(q).join(', ')}]::text[]`;
const jsonb = (obj) => `${q(JSON.stringify(obj ?? {}))}::jsonb`;

const files = readdirSync(plannerDir)
  .filter((f) => /^month-\d+\.json$/.test(f))
  .sort();

let sql = `-- Generated by scripts/gen-seed-sql.mjs — do not edit by hand.\n`;
sql += `-- Seeds all months + days as PUBLISHED. Safe to re-run (upserts on the\n`;
sql += `-- natural keys month_number / day_number).\n\nbegin;\n\n`;

let dayCount = 0;
for (const file of files) {
  const m = JSON.parse(readFileSync(`${plannerDir}/${file}`, 'utf8'));
  sql += `-- Month ${m.month}: ${m.title}\n`;
  sql +=
    `insert into public.months (month_number, title, goal, project, status)\n` +
    `values (${m.month}, ${q(m.title)}, ${q(m.goal)}, ${jsonb(m.project)}, 'published')\n` +
    `on conflict (month_number) do update set\n` +
    `  title = excluded.title, goal = excluded.goal, project = excluded.project, status = excluded.status;\n\n`;

  for (const d of m.days) {
    dayCount += 1;
    sql +=
      `insert into public.days (month_id, day_number, title, duration, learning_objective, ` +
      `videos, docs, reading, practice, tasks, mini_project, interview_questions, status)\n` +
      `values ((select id from public.months where month_number = ${m.month}), ` +
      `${d.day}, ${q(d.title)}, ${q(d.duration)}, ${q(d.learningObjective)}, ` +
      `${arr(d.videos)}, ${arr(d.docs)}, ${arr(d.reading)}, ${arr(d.practice)}, ${arr(d.tasks)}, ` +
      `${q(d.miniProject)}, ${arr(d.interviewQuestions)}, 'published')\n` +
      `on conflict (day_number) do update set\n` +
      `  month_id = excluded.month_id, title = excluded.title, duration = excluded.duration,\n` +
      `  learning_objective = excluded.learning_objective, videos = excluded.videos, docs = excluded.docs,\n` +
      `  reading = excluded.reading, practice = excluded.practice, tasks = excluded.tasks,\n` +
      `  mini_project = excluded.mini_project, interview_questions = excluded.interview_questions,\n` +
      `  status = excluded.status;\n`;
  }
  sql += `\n`;
}

sql += `commit;\n`;
writeFileSync(outFile, sql);
console.log(`Wrote ${outFile}: ${files.length} months, ${dayCount} days.`);
