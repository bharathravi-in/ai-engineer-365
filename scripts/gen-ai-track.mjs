// Rebuilds the `ai-engineer` track from the 12-month planner (planner/*.json):
// 12 modules (one per month) and 360 topics (one per day), each enriched with
// reference docs (canonical, per technology) and a video link. Emits
// supabase/seed_ai_track.sql. Idempotent: it replaces the track's modules.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const q = (s) => `'${String(s ?? '').replace(/'/g, "''")}'`;
const jb = (o) => `${q(JSON.stringify(o ?? []))}::jsonb`;
const yt = (title) => `https://www.youtube.com/results?search_query=${encodeURIComponent(title + ' tutorial')}`;

// Canonical reference docs per month (real, official / well-known sources).
const MONTH_DOCS = {
  1: [ ['doc', 'PostgreSQL Documentation', 'https://www.postgresql.org/docs/current/'], ['article', 'PostgreSQL Tutorial', 'https://www.postgresqltutorial.com/'] ],
  2: [ ['doc', 'Python Tutorial', 'https://docs.python.org/3/tutorial/'], ['article', 'Real Python', 'https://realpython.com/'] ],
  3: [ ['doc', 'FastAPI', 'https://fastapi.tiangolo.com/'], ['doc', 'Redis Documentation', 'https://redis.io/docs/latest/'] ],
  4: [ ['doc', 'Docker Documentation', 'https://docs.docker.com/'], ['doc', 'Kubernetes Documentation', 'https://kubernetes.io/docs/home/'] ],
  5: [ ['doc', 'Anthropic: Intro to Claude', 'https://docs.claude.com/en/docs/intro-to-claude'], ['doc', 'NumPy: Beginners', 'https://numpy.org/doc/stable/user/absolute_beginners.html'] ],
  6: [ ['doc', 'Anthropic: Search & Retrieval (RAG)', 'https://docs.claude.com/en/docs/build-with-claude/search-and-retrieval'], ['repo', 'pgvector', 'https://github.com/pgvector/pgvector'] ],
  7: [ ['doc', 'LangGraph', 'https://langchain-ai.github.io/langgraph/'], ['doc', 'Model Context Protocol', 'https://modelcontextprotocol.io/'] ],
  8: [ ['doc', 'ClickHouse Documentation', 'https://clickhouse.com/docs'], ['doc', 'Apache Kafka Documentation', 'https://kafka.apache.org/documentation/'] ],
  9: [ ['doc', 'Elasticsearch Guide', 'https://www.elastic.co/guide/en/elasticsearch/reference/current/index.html'], ['doc', 'Neo4j Documentation', 'https://neo4j.com/docs/'] ],
  10: [ ['doc', 'AWS Documentation', 'https://docs.aws.amazon.com/'], ['doc', 'Google Cloud Documentation', 'https://cloud.google.com/docs'] ],
  11: [ ['repo', 'System Design Primer', 'https://github.com/donnemartin/system-design-primer'], ['doc', 'Anthropic: Define success criteria', 'https://docs.claude.com/en/docs/test-and-evaluate/define-success'] ],
  12: [ ['article', 'The Twelve-Factor App', 'https://12factor.net/'], ['doc', 'Anthropic Documentation', 'https://docs.claude.com/en/docs/intro-to-claude'] ],
};

const SUBTITLE = '12-month path: databases → Python → APIs → LLMs → RAG → agents → production';
const DESCRIPTION =
  'The full AI engineering journey — PostgreSQL, Python, FastAPI & Redis, Docker & Kubernetes, ' +
  'LLMs, RAG, agents (LangGraph/MCP), streaming data, search & graph, cloud, system design & ' +
  'evaluation, and a production AI SaaS capstone. 360 day-sized concepts with reference docs and videos.';

let sql = `-- Generated by scripts/gen-ai-track.mjs — do not edit by hand.\n`;
sql += `-- Rebuilds the ai-engineer track from the 12-month planner. Safe to re-run.\nbegin;\n\n`;

// Update the track meta (keep icon/color from the original seed).
sql += `update public.tracks set subtitle=${q(SUBTITLE)}, description=${q(DESCRIPTION)}, difficulty='Beginner → Advanced', status='published' where slug='ai-engineer';\n\n`;
// Replace its modules (cascades to topics + any progress on old topics).
sql += `delete from public.modules where track_id = (select id from public.tracks where slug='ai-engineer');\n\n`;

let topicCount = 0;
for (let mi = 1; mi <= 12; mi++) {
  const m = JSON.parse(readFileSync(join(root, 'planner', `month-${String(mi).padStart(2, '0')}.json`), 'utf8'));
  const modSlug = `month-${m.month}`;
  sql +=
    `insert into public.modules (track_id, slug, title, goal, sort_order)\n` +
    `values ((select id from public.tracks where slug='ai-engineer'), ${q(modSlug)}, ${q(`Month ${m.month}: ${m.title}`)}, ${q(m.goal)}, ${m.month - 1});\n`;

  for (let di = 0; di < m.days.length; di++) {
    const d = m.days[di];
    topicCount += 1;
    const hours = parseFloat(d.duration) || 2;
    const desc =
      (d.learningObjective || '') +
      (Array.isArray(d.practice) && d.practice.length ? ` Practice: ${d.practice.join('; ')}.` : '');
    const resources = [
      ...MONTH_DOCS[m.month].map(([kind, title, url]) => ({ kind, title, url })),
      { kind: 'video', title: `Video: ${d.title}`, url: yt(d.title) },
    ];
    sql +=
      `insert into public.topics (module_id, slug, title, description, est_hours, resources, status, sort_order)\n` +
      `values ((select mo.id from public.modules mo join public.tracks tr on tr.id=mo.track_id where tr.slug='ai-engineer' and mo.slug=${q(modSlug)}), ` +
      `${q(`day-${d.day}`)}, ${q(`Day ${d.day}: ${d.title}`)}, ${q(desc)}, ${hours}, ${jb(resources)}, 'published', ${di});\n`;
  }
  sql += `\n`;
}

sql += `commit;\n`;
const out = join(root, 'supabase', 'seed_ai_track.sql');
writeFileSync(out, sql);
console.log(`Wrote ${out}: 12 modules, ${topicCount} topics.`);
